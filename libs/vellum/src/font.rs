pub fn glyph(ch: u8) -> &'static [u8; 8] {
    if ch < 128 { &FONT[ch as usize] } else { &FONT[b'?' as usize] }
}

pub fn draw_char<C: Canvas>(canvas: &mut C, x: i32, y: i32, ch: u8, scale: u32, color: Color) {
    let bitmap = glyph(ch);
    for row in 0..GLYPH_H {
        let bits = bitmap[row as usize];
        for column in 0..GLYPH_W {
            if bits >> column & 1 == 0 {
                continue;
            }
            for sy in 0..scale {
                for sx in 0..scale {
                    let px = x + (column * scale + sx) as i32;
                    let py = y + (row * scale + sy) as i32;
                    if px >= 0 && py >= 0 {
                        canvas.set_pixel(px as u32, py as u32, color);
                    }
                }
            }
        }
    }
}

pub fn draw_text<C: Canvas>(canvas: &mut C, x: i32, y: i32, text: &str, scale: u32, color: Color) {
    let mut cursor = x;
    for ch in text.chars() {
        let byte = if ch.is_ascii() { ch as u8 } else { b'?' };
        draw_char(canvas, cursor, y, byte, scale, color);
        cursor += (GLYPH_W * scale) as i32;
    }
}

pub fn text_width(text: &str, scale: u32) -> u32 {
    text.chars().count() as u32 * GLYPH_W * scale
}
