import os
import re
import sys

PATTERN = re.compile(r"^\s*(?:pub\s+)?const\s+([A-Z][A-Z0-9_]*)\s*:\s*([^=]+?)\s*=\s*(.+?);\s*$")
FILES = ["anim.rs", "wm.rs", "render.rs", "chrome.rs", "dock.rs", "panel.rs", "launcher.rs", "desktop.rs", "sound.rs", "shell.rs", "main.rs"]

roots = sys.argv[1:]
print("# Nook: parameters of the golden reference")
print()
print("Generated by `cargo xtask golden --update` from `userland/desktop/hxserver/src` and `userland/desktop/nook-shell/src`.")
print("A change here is a deliberate change of Nook's look or motion.")
print()
print("| File | Constant | Type | Value |")
print("|---|---|---|---|")
for root in roots:
    crate = os.path.basename(os.path.dirname(os.path.abspath(root)))
    for name in FILES:
        path = os.path.join(root, name)
        if not os.path.exists(path):
            continue
        for line in open(path, encoding="utf-8"):
            m = PATTERN.match(line)
            if m:
                value = m.group(3).replace("|", "\\|")
                print("| %s/%s | %s | %s | `%s` |" % (crate, name, m.group(1), m.group(2).strip(), value))
